/**
 * data/templates.js —— 内置人设模板库
 *
 * 定位：本文件是「AI 好友通讯录」的开箱内容。用户点开模板库 → 选一个模板 →
 * `templateToCharacter()` 直接生成一张符合 ARCHITECTURE.md §2.1 契约的完整角色卡，
 * 之后在角色编辑器里随便改。
 *
 * 契约说明：
 * - 模板对象 = Character 契约字段 + 4 个纯展示字段（templateId / templateName / group / blurb）。
 *   注意：模板上的 `group` 是**模板库分组 id**（daily/work/...），
 *   而 Character.group 是**通讯录分组名**（默认 '默认'）；转换时由 GROUP_NAME 映射。
 * - 模板的 `voice` 只给建议的 rate/pitch（provider/voiceId 留空），
 *   `templateToCharacter()` 会补全成完整的 VoiceConfig。
 * - 所有 schema 字段都补全为字符串，绝不出现 undefined（prompt 装配不会踩空）。
 *
 * 技术基线：原生 ES Module、零依赖、零构建、无 CDN、2 空格缩进、中文注释。
 */

/**
 * @typedef {Object} TemplatePersona
 * @property {string} personality 性格关键词
 * @property {string} mbti MBTI
 * @property {string} values 价值观 / 行为动机
 * @property {string} style 说话风格（口语/书面/方言…）
 * @property {string} catchphrase 口头禅
 * @property {string} emojiHabit 常用表情与标点习惯
 * @property {string} particles 语气助词
 * @property {string} relationship 与用户的关系
 * @property {string} addressUser 称呼用户的方式
 * @property {string} world 世界观 / 时代背景
 * @property {string} place 常驻地点
 * @property {string} speech 具体语言习惯（句式、节奏、禁忌用法）
 * @property {string} taboo 禁区话题
 */

/**
 * @typedef {Object} Template
 * @property {string} id 模板 id（tpl_xxx，全局唯一）
 * @property {string} templateName 模板展示名
 * @property {string} group 模板库分组 id
 * @property {string} blurb 列表页一句话
 * @property {string} name 角色名
 * @property {string} avatar 头像（模板一律留空，用 emoji）
 * @property {string} emoji 无头像时的表情
 * @property {string} color 主题色
 * @property {string} gender 性别
 * @property {string} age 年龄
 * @property {string} job 职业 / 身份
 * @property {string} tagline 一句话简介
 * @property {string[]} tags 标签
 * @property {TemplatePersona} persona 人设详情
 * @property {string} systemPrompt 完整系统提示词（留空则由 persona 自动装配）
 * @property {Array<{user: string, ai: string}>} examples few-shot 示例
 * @property {string} authorNote 作者备注
 * @property {number} affinity 初始好感度
 * @property {string[]} greeting 开场白
 * @property {{rate: number, pitch: number}} voice 建议声线
 */

